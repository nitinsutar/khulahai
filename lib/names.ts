export function shortName(rbi: string, l: 'en' | 'hi' = 'en'): string {
  const m = MAP[rbi];
  if (m) return l === 'hi' ? m[1] : m[0];
  return rbi.split('/').slice(0, 2).join(' / ');
}
export const isFullName = (rbi: string) => !MAP[rbi] && rbi.split('/').length <= 2;
